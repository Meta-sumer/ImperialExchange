/**
 * Bundles the chart WebView runtime (src/charts/runtime/*.js) into a TS
 * module the app can import as a string.
 *
 * The runtime is plain JavaScript on purpose: it runs INSIDE the WebView,
 * where Metro does not reach, and jest loads the same files directly to test
 * them. This script is the only bridge between the two — run it after
 * editing any runtime file (postinstall runs it too):
 *
 *   node scripts/build-chart-runtime.mjs
 *
 * src/__tests__/stage5_chartRuntime.test.ts fails when the generated module
 * is out of date, so a forgotten rebuild cannot ship.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '..', 'src', 'charts', 'runtime');

// Order matters: chart.js reads the namespaces the others define.
export const RUNTIME_FILES = ['indicators.js', 'candles.js', 'drawings.js', 'chart.js'];

export const bundleRuntime = () =>
  RUNTIME_FILES.map((f) => `/* ── ${f} ── */\n${readFileSync(join(dir, f), 'utf8')}`).join('\n;\n');

const banner = [
  '/* eslint-disable */',
  '// AUTO-GENERATED by scripts/build-chart-runtime.mjs — do not edit.',
  `// Source: src/charts/runtime/{${RUNTIME_FILES.join(',')}}`,
  '',
].join('\n');

const main = () => {
  const source = bundleRuntime();
  const body = [
    `export const CHART_RUNTIME_FILES: readonly string[] = ${JSON.stringify(RUNTIME_FILES)};`,
    '',
    `export const CHART_RUNTIME_SOURCE: string = ${JSON.stringify(source)};`,
    '',
  ].join('\n');
  writeFileSync(join(dir, 'generated.ts'), `${banner}${body}`, 'utf8');
  console.log(`[chart-runtime] wrote generated.ts (${Math.round(source.length / 1024)} KB)`);
};

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
