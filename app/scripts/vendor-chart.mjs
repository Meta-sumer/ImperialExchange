/**
 * Vendors the charting library into the app bundle.
 *
 * The chart renders inside a WebView, which needs the library as SOURCE it
 * can evaluate. Pulling it from a CDN at runtime would mean a trader with
 * no signal gets no chart — unacceptable for an app whose whole job is to
 * work on a train. So the standalone build is copied into a TS module at
 * install time and the WebView receives it inline.
 *
 * Runs on postinstall. Re-run manually after changing the library version:
 *   node scripts/vendor-chart.mjs
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

const SOURCE = join(
  root,
  'node_modules',
  'lightweight-charts',
  'dist',
  'lightweight-charts.standalone.production.js',
);
const OUT_DIR = join(root, 'src', 'charts', 'vendor');
const OUT_FILE = join(OUT_DIR, 'chartLibrary.ts');

if (!existsSync(SOURCE)) {
  console.warn(
    '[vendor-chart] lightweight-charts not installed yet — keeping placeholder. Run "npm install" first.',
  );
  process.exit(0);
}

const source = readFileSync(SOURCE, 'utf8');

// JSON.stringify emits a correctly escaped JS string literal. Hand-rolling
// the escaping for a minified bundle full of backslashes, backticks and
// template-literal sequences is a reliable way to produce a corrupt file.
const literal = JSON.stringify(source);

const banner = [
  '/* eslint-disable */',
  '// AUTO-GENERATED by scripts/vendor-chart.mjs — do not edit.',
  '// Source: lightweight-charts (standalone production build).',
  '',
].join('\n');

const body = [
  `export const CHART_LIBRARY_SOURCE: string = ${literal};`,
  '',
  'export const isChartLibraryVendored = (): boolean => CHART_LIBRARY_SOURCE.length > 0;',
  '',
].join('\n');

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT_FILE, `${banner}${body}`, 'utf8');

console.log(`[vendor-chart] wrote chartLibrary.ts (${Math.round(source.length / 1024)} KB)`);
